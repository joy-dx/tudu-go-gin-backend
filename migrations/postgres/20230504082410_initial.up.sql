CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username VARCHAR(255) NOT NULL,
                       password VARCHAR(255),
                       roles TEXT[],
                       status TEXT
);

--bun:split

CREATE TABLE todos (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       title VARCHAR(255) NOT NULL,
                       content TEXT,
                       complete BOOLEAN NOT NULL DEFAULT FALSE
);